// Pulls the React UMD bundles that support.js would otherwise fetch from
// unpkg.com at runtime, and writes the small shim that points the dc-runtime at
// the local copies instead.
//
// Why: support.js's loadReactUmd() injects two <script> tags pointing at
// unpkg.com whenever window.React is missing — which is every cold page load.
// That puts a third-party CDN on the critical render path: an unpkg outage
// leaves every URL on the site a blank page, and even on a good day it costs a
// DNS + TLS + fetch round trip to another origin before the app can boot.
// Same reasoning as scripts/fetch-fonts.mjs, same fix.
//
// The runtime supports this officially: cdnScriptFor() checks
// window.__resources[cdnUrl] first and uses that src when it is a non-empty
// string, falling back to the CDN otherwise. So the shim below is all it takes.
//
// URLs and SRI hashes are read out of support.js rather than hardcoded, so a
// regenerated runtime that bumps React is picked up by re-running this script.
// Each download is verified against the hash support.js already commits to.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const runtime = readFileSync('support.js', 'utf8');

// var REACT_URL = "https://unpkg.com/react@18.3.1/umd/react.production.min.js";
// var REACT_SRI = "sha384-...";
function pick(name) {
  const url = runtime.match(new RegExp(`var ${name}_URL = "([^"]+)"`));
  const sri = runtime.match(new RegExp(`var ${name}_SRI = "([^"]+)"`));
  if (!url || !sri) throw new Error(`could not read ${name}_URL / ${name}_SRI out of support.js`);
  return { url: url[1], sri: sri[1] };
}

// Babel is deliberately not mirrored: ensureBabel() only runs for JSX x-import,
// which this site does not use. If that ever changes, add 'BABEL' here.
const DEPS = [pick('REACT'), pick('REACT_DOM')];

mkdirSync('assets/vendor', { recursive: true });

const map = {};
let total = 0;

for (const { url, sri } of DEPS) {
  const res = await fetch(url, { redirect: 'follow' });
  if (!res.ok) throw new Error(`${url} -> HTTP ${res.status}`);
  const bin = Buffer.from(await res.arrayBuffer());

  const [algo, expected] = sri.split('-');
  const actual = createHash(algo).update(bin).digest('base64');
  if (actual !== expected) {
    throw new Error(`integrity mismatch for ${url}\n  expected ${algo}-${expected}\n  got      ${algo}-${actual}`);
  }

  // react@18.3.1/umd/react.production.min.js -> react-18.3.1.js
  const [, name, version] = url.match(/unpkg\.com\/([^@]+)@([^/]+)\//);
  const file = `${name}-${version}.js`;
  writeFileSync(`assets/vendor/${file}`, bin);
  map[url] = `/assets/vendor/${file}`;
  total += bin.length;
  console.log(`${file.padEnd(28)} ${(bin.length / 1024).toFixed(1)} KiB  ${algo} ok`);
}

// Without a preload the browser only learns about React once support.js has
// parsed and injected the tags — a two-hop waterfall before the app can boot.
// These tags are rewritten in place on every run (same trick build-pages.mjs
// uses for its hreflang/noscript blocks), so a React bump can't leave a stale
// path behind.
const MARK_OPEN = '<!-- vendor-preload:start -->';
const MARK_CLOSE = '<!-- vendor-preload:end -->';
const preloads = [
  MARK_OPEN,
  ...Object.values(map).map((p) => `<link rel="preload" href="${p}" as="script">`),
  MARK_CLOSE,
].join('\n');

let page = readFileSync('index.html', 'utf8');
page = page.replace(new RegExp(`${MARK_OPEN}[\\s\\S]*?${MARK_CLOSE}\\n?`), '');
if (!page.includes('<script src="/assets/vendor.js" defer></script>')) {
  throw new Error('index.html does not load /assets/vendor.js — add that <script> tag first');
}
page = page.replace(
  '<script src="/assets/vendor.js" defer></script>',
  `${preloads}\n<script src="/assets/vendor.js" defer></script>`,
);
writeFileSync('index.html', page);
console.log(`\nrefreshed ${Object.keys(map).length} preload tags in index.html`);

const shim = `// Generated by scripts/fetch-vendor.mjs — do not edit.
//
// Redirects the dc-runtime's React bootstrap at self-hosted copies. support.js
// reads window.__resources[cdnUrl] in cdnScriptFor() and uses that src when it
// is set, so this keeps unpkg.com off the critical path (and out of the CSP).
//
// Must run before support.js. Both tags are \`defer\`, and deferred scripts
// execute in document order, so placing this one first in <head> is enough.
window.__resources = Object.assign(window.__resources || {}, ${JSON.stringify(map, null, 2)});
`;

writeFileSync('assets/vendor.js', shim);
console.log(`\n${(total / 1024).toFixed(1)} KiB self-hosted -> assets/vendor.js`);
